def seed():
    init_db()
    with get_connection() as conn:
        cursor = conn.cursor()
        
        # Check existing count
        cursor.execute("SELECT COUNT(*) FROM prospects")
        count = cursor.fetchone()[0]
        if count > 0:
            print(f"Database already contains {count} prospects. Skipping seed.")
            return

        now = datetime.now().isoformat()
        inserted = 0

        for p in PROSPECTS_DATA:
            # Score prospect
            scores = score_prospect(
                category=p['category'],
                link_type=p['link_type'],
                is_local_sambhajinagar=p.get('is_local_sambhajinagar', False),
                is_maharashtra_regional=p.get('is_maharashtra_regional', False),
                has_editorial_review=p.get('has_editorial_review', True),
                has_verified_contact=p.get('has_verified_contact', True),
                traffic_tier=p.get('traffic_tier', 'medium')
            )

            # Generate outreach draft
            draft = generate_outreach_draft(p)

            # Follow up date: 7 days from now for directory citations, 14 days for editorials
            days_delay = 7 if p['link_type'] in ['directory_citation', 'local_citation'] else 14
            follow_up = (datetime.now() + timedelta(days=days_delay)).strftime("%Y-%m-%d")

            cursor.execute("""
            INSERT INTO prospects (
                domain, url, title, category, link_type,
                relevance_score, audience_score, legitimacy_score, editorial_score,
                spam_penalty, total_score, spam_risk, status,
                contact_name, contact_email, contact_url, target_page,
                outreach_angle, outreach_draft_subject, outreach_draft_body,
                human_approved, follow_up_date, notes, created_at, updated_at
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            """, (
                p['domain'], p['url'], p['title'], p['category'], p['link_type'],
                scores['relevance_score'], scores['audience_score'], scores['legitimacy_score'], scores['editorial_score'],
                scores['spam_penalty'], scores['total_score'], scores['spam_risk'], scores['recommended_status'],
                p.get('contact_name'), p.get('contact_email'), p.get('contact_url'), p.get('target_page', 'https://myjuice.in/'),
                p.get('outreach_angle'), draft['subject'], draft['body'],
                0, # human_approved = 0 (Pending review)
                follow_up,
                f"Discovered via Phase 2 AI SEO Audit. Traffic tier: {p.get('traffic_tier')}",
                now, now
            ))
            inserted += 1

        conn.commit()
        log_action(f"Seeded {inserted} verified backlink prospects into SQLite database", "system", 0, "Phase 2 Prospect Discovery")
        print(f"Successfully seeded {inserted} prospects into seo_agent.db!")

if __name__ == '__main__':
    seed()
